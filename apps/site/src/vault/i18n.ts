type Texts = (typeof TEXT)["en"];
export type TextKey = Exclude<keyof Texts, "errors">;
export type ErrorKey = keyof Texts["errors"];

export const lang: Lang = (() => {
  try {
    const stored = localStorage.getItem("lang");
    if (stored === "pt-BR" || stored === "en" || stored === "es") return stored;
  } catch {
    // Storage blocked: the browser's languages decide.
  }
  for (const l of navigator.languages ?? [navigator.language]) {
    const lower = l.toLowerCase();
    if (lower.startsWith("pt")) return "pt-BR";
    if (lower.startsWith("es")) return "es";
    if (lower.startsWith("en")) return "en";
  }
  return "en";
})();

const fill = (text: string, vars: Record<string, string | number>) => text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));

export const t = (key: TextKey, vars: Record<string, string | number> = {}) => fill(TEXT[lang][key] as string, vars);

/** An error's text: a known key, or the generic one with the message. */
export function errorText(key: string, message = ""): string {
  const errors = TEXT[lang].errors as Record<string, string>;
  return errors[key] ?? fill(errors.unknown, { message: message || key });
}

export const fieldLabel = (label: string) => labels[lang].fieldLabels[label] ?? label;
export const categoryLabel = (category: string) => labels[lang].categories[category] ?? category;
export const categoryPlural = (category: string) => labels[lang].categoriesPlural[category] ?? categoryLabel(category);
export const formatDate = (unixSeconds: number) =>
  new Date(unixSeconds * 1000).toLocaleString(lang, { dateStyle: "medium", timeStyle: "short" });
